//! UI commands produced by the application layer and executed by the Qt layer.
//!
//! Commands are plain data and never hold a borrow of `AppState`, which keeps
//! dialogs and other re-entrant Qt callbacks safe.

#[derive(Debug, Clone)]
pub enum UiCommand {
    Menus(String),
    TagSuggestions(String),
    Autocomplete(String),
    BuildPages(String),
    UpdatePage(String, String),
    PageProgress(String, String),
    Defer {
        action: String,
        target: String,
        payload: String,
        delay_ms: i32,
    },
    UpdateDownloader(String, String),
    UpdateSubscriptions(String, String),
    UpdateDuplicates(String, String),
    UpdateImportFolders(String, String),
    DuplicatesRulesDialog(String),
    TagRelationsDialog(String),
    ImportFolderDialog(String),
    SetSelection {
        page_id: String,
        hash: String,
        tags_json: String,
        preview_path: String,
        metadata_json: String,
    },
    Status(String),
    ShowPageChooser(String),
    PageManagerDialog(String),
    CommandPalette,
    PromptText {
        action: String,
        title: String,
        label: String,
        initial: String,
    },
    ConfirmAction {
        action: String,
        target: String,
        title: String,
        text: String,
    },
    PromptOr {
        page_id: String,
        initial: String,
    },
    NotificationsDialog(String),
    ViewingStatsDialog(String),
    AboutDialog(String),
    ExportDownloader(String),
    ImportDownloader(String),
    PickFiles,
    PromptUrl,
    OpenViewer(String),
    UpdateViewer(String, String),
    CloseViewer(String),
    TagDialog(String),
    ManageTagsDialog(String),
    TimestampsDialog(String),
    NotesDialog(String),
    OptionsDialog(String),
    ServicesDialog(String),
    NetworkDialog(String),
    NotifyMessage(String),
    Message(String, String),
    OpenPath(String),
    OpenUrl(String),
    Screenshot(String),
    Quit,
}
