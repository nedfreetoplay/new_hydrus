//! UI commands produced by the application layer and executed by the Qt layer.
//!
//! Commands are plain data and never hold a borrow of `AppState`, which keeps
//! dialogs and other re-entrant Qt callbacks safe.
//!
//! Typed seams (WS-15.2.1) carry shared structs from `crate::gui::qt::api`
//! instead of JSON strings; the remaining `String` payloads are converted
//! per screen in WS-15.2.2.

use crate::gui::qt::api::ffi::{
    AboutInfo, DownloaderPageState, FileSeedCacheState, GallerySeedLogState, ImportOptionsDialogState,
    MenuBar, PageProgress, PageTree, Pages, QueryPageState, SelectionState, StatusBar,
    SubscriptionsDialogState, SubscriptionsPageState, SubscriptionEditorState, ViewerState,
    ViewingStats,
};

#[derive(Debug, Clone)]
pub enum UiCommand {
    Menus(MenuBar),
    TagSuggestions(String),
    Autocomplete(String),
    BuildPages(Pages),
    UpdatePage(QueryPageState),
    PageProgress(PageProgress),
    Defer {
        action: String,
        target: String,
        payload: String,
        delay_ms: i32,
    },
    UpdateDownloader(DownloaderPageState),
    UpdateSubscriptions(SubscriptionsPageState),
    SubscriptionsDialog(SubscriptionsDialogState),
    UpdateSubscriptionsDialog(SubscriptionsDialogState),
    SubscriptionEditor(SubscriptionEditorState),
    UpdateDuplicates(String, String),
    UpdateImportFolders(String, String),
    ImportFoldersDialog(String),
    UpdateImportFoldersDialog(String),
    UpdateExportFolders(String, String),
    ExportFoldersDialog(String),
    UpdateExportFoldersDialog(String),
    DuplicatesRulesDialog(String),
    DuplicatesMergeOptionsDialog(String),
    DuplicateCustomActionDialog(String),
    DuplicatesRulePreview(String),
    DuplicateReviewDialog(String),
    UpdateDuplicateReview(String),
    TagRelationsDialog(String),
    ImportFolderDialog(String),
    LocalImportReviewDialog(String),
    LocalImportTaggingDialog(String),
    CloseLocalImportReview,
    RepairFileLocationsDialog(String),
    CloseRepairFileLocations,
    ExportFolderDialog(String),
    ExportReviewDialog(String),
    SetSelection(SelectionState),
    Status(StatusBar),
    ShowPageChooser(String),
    PageManagerDialog(PageTree),
    CommandPalette,
    PromptText {
        action: String,
        title: String,
        label: String,
        initial: String,
    },
    ConfirmAction {
        action: String,
        target: String,
        title: String,
        text: String,
    },
    PromptOr {
        page_id: String,
        initial: String,
    },
    NotificationsDialog(String),
    ViewingStatsDialog(ViewingStats),
    AboutDialog(AboutInfo),
    ExportDownloader(String),
    FileSeedCacheDialog(FileSeedCacheState),
    GallerySeedLogDialog(GallerySeedLogState),
    ImportDownloader(String),
    PickFiles,
    PromptUrl,
    OpenViewer(ViewerState),
    UpdateViewer(ViewerState),
    CloseViewer(String),
    TagDialog(String),
    ManageTagsDialog(String),
    TimestampsDialog(String),
    NotesDialog(String),
    ImportOptionsDialog(ImportOptionsDialogState),
    OptionsDialog(String),
    ServicesDialog(String),
    UpdateServices(String),
    TagFilterDialog(String),
    ApiPermissionsDialog(String),
    UpdateApiPermissions(String),
    AccountTypesDialog(String),
    UpdateAccountTypes(String),
    OrphanFilesDialog(String),
    UpdateOrphanFiles(String),
    DatabaseBackupDialog(String),
    UpdateDatabaseBackup(String),
    NetworkDialog(String),
    NotifyMessage(String),
    SetClipboard(String),
    Message(String, String),
    OpenPath(String),
    OpenUrl(String),
    Screenshot(String),
    Quit,
}
